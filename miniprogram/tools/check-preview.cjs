const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const vm = require('node:vm');
const root = path.resolve(__dirname, '..');
const preview = path.resolve(root, '../.claude/verification/native-miniprogram/offline-preview');
const liveApp = fs.readFileSync(path.join(root, 'src/app.js'), 'utf8');
assert(!liveApp.includes('offline-fixture'), 'Fixture was inserted into production app');
assert(!fs.existsSync(path.join(root, 'src/offline-fixture.js')), 'Fixture leaked into production source');
const fixtureFile = path.join(preview, 'src/offline-fixture.js');
assert(fs.existsSync(fixtureFile), 'Run make-preview.cjs first');
new vm.Script(fs.readFileSync(fixtureFile, 'utf8'));
assert.equal(JSON.parse(fs.readFileSync(path.join(preview, 'project.config.json'))).appid, JSON.parse(fs.readFileSync(path.join(root, 'project.config.json'))).appid, 'Preview must use the authorized app id; current tools reject touristappid');
const fixture = require(fixtureFile);
const request = (method, route, data) => new Promise(resolve => fixture.request({ url: 'https://offline-preview.invalid/api' + route, method, data, success: resolve }));
(async () => {
  const tasks = await request('GET', '/tasks');
  assert(tasks.data.data.length >= 3);
  const login = await request('POST', '/auth/login', { username: 'local', password: 'local' });
  assert.equal(login.data.data.accessToken, 'offline-not-a-real-token');
  const role = await request('POST', '/identity/users/900001/roles', { roleType: 'SHOP_MERCHANT', agreementVersion: '离线样例' });
  assert.equal(role.data.data.reviewStatus, 'PENDING_REVIEW');
  const applications = await request('GET', '/identity/users/900001/roles');
  assert.equal(applications.data.data.length, 1);
  assert.equal(applications.data.data[0].reviewStatus, 'PENDING_REVIEW');
  const session = await request('GET', '/auth/me');
  assert(!session.data.data.roles.includes('ROLE_SHOP_MERCHANT'));
  const forbidden = await request('POST', '/payment/anything');
  assert.equal(forbidden.statusCode, 400);
  console.log('PASS separate preview syntax and sample flow; production source has no fixtures; no network used.');
})().catch(error => { console.error(error.stack); process.exitCode = 1; });
